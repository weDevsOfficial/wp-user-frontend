const compile = async ( css, from ) =>
    ( await postcss( [ tailwind( { base: here, optimize: { minify: true } } ) ] ).process( css, { from } ) ).css;

const skip = ( rule ) => rule.parent && 'atrule' === rule.parent.type && /keyframes/.test( rule.parent.name );

/**
 * Scope the utilities to the screen's body class with zero specificity.
 *
 * Text colour utilities also get an `html … a.text-…` selector (0,1,2):
 * WordPress paints links blue on hover and focus with `a:hover` / `a:focus`
 * (0,1,1; the admin colour scheme prints after this sheet), which beat the
 * plain class (0,1,0), so a clicked tab or link stayed admin blue. The link
 * keeps its own colour; the screen's own `hover:` / `focus:` utilities (0,2,0)
 * still win (owner 2026-10-07: no blue hover or focus on the React screens).
 *
 * @param {Object} layer Utilities layer.
 * @param {string} scope Body class selector.
 */
function scopeUtilities( layer, scope ) {
    layer.walkRules( ( rule ) => {
        if ( skip( rule ) ) {
            return;
        }

        const colors = rule.some( ( decl ) => 'decl' === decl.type && 'color' === decl.prop );

        rule.selectors = rule.selectors.flatMap( ( selector ) => {
            const trimmed = selector.trim();
            const scoped = `:where(${ scope }) ${ trimmed }`;

            return colors && /^\.text-[^\s:>+~]+$/.test( trimmed ) ? [ scoped, `html :where(${ scope }) a${ trimmed }` ] : [ scoped ];
        } );
    } );
}

/**
 * Unwrap every `@layer` (keeping order), drop Tailwind 4's own base layer and
 * put the Tailwind 3 base in its place.
 */
/**
 * Rendering details pinned to Tailwind 3: `rounded-full` is 9999px (Tailwind 4:
 * calc(infinity * 1px), which anti-aliases curved edges differently), colors
 * with an opacity modifier keep the hex + alpha value (Tailwind 4 adds an
 * `@supports (color-mix)` override mixing in oklab) and gradients interpolate
 * in sRGB.
 */
function pinV3Rendering( tree ) {
    tree.walkAtRules( 'supports', ( rule ) => {
        if ( /color-mix/.test( rule.params ) ) {
            rule.remove();
        }
    } );
    tree.walkDecls( ( decl ) => {
        if ( /^border(-[a-z]+)*-radius$/.test( decl.prop ) && /3\.40282e38px|calc\(infinity/.test( decl.value ) ) {
            decl.value = '9999px';
        }
        // Gradients interpolate in sRGB as in Tailwind 3 (Tailwind 4: `in oklab`).
        if ( '--tw-gradient-position' === decl.prop ) {
            decl.value = decl.value.replace( /\s+in\s+oklab/, '' );
        }
    } );
}

function flatten( css, baseNodes, postNodes, scope ) {
    const tree = postcss.parse( css );
    pinV3Rendering( tree );
    const out = postcss.root();
    let based = false;
    const putBase = () => {
        if ( ! based ) {
            baseNodes.forEach( ( node ) => out.append( node.clone() ) );
            based = true;
        }
    };

    tree.each( ( node ) => {
        if ( 'atrule' !== node.type || 'layer' !== node.name ) {
            out.append( node.clone() );
            return;
        }
        if ( ! node.nodes ) {
            return; // `@layer a, b;` order statement.
        }
        if ( 'base' === node.params ) {
            putBase();
            return;
        }
        if ( 'utilities' === node.params ) {
            putBase();
            scopeUtilities( node, scope );
            node.each( ( child ) => out.append( child.clone() ) );
            postNodes.forEach( ( child ) => out.append( child.clone() ) );
            postNodes = [];
            return;
        }
        node.each( ( child ) => out.append( child.clone() ) );
    } );

    putBase();
    postNodes.forEach( ( node ) => out.append( node.clone() ) );

    // Tailwind 3: text-* sets line-height outright, so whichever of text-* /
    // leading-* comes later in the cascade wins (`leading-none sm:text-sm` gets
    // the sm line height). Tailwind 4 writes var(--tw-leading, …) instead.
    return out
        .toResult( { map: false } )
        .css.replace( /line-height:\s*var\(--tw-leading,\s*var\((--text-[\w-]+--line-height)\)\)/g, 'line-height:var($1)' );
}

/**
 * The plugin-ui part (src/pui.css) for a screen with `pui: true`: its theme
 * variables move from :root to `.pui-root` (the screen's own Tailwind 3
 * values stay on :root), its utilities (`!important`) apply to `.pui-root`
 * and everything inside it (portals included), its preflight stays nested
 * under `.pui-root`. Cascade layers are flattened like the screen part.
 */
// The WordPress editor (TinyMCE + Quicktags, WpEditor) keeps WordPress's own
// look inside plugin-ui screens: plugin-ui's preflight, base and form resets
// skip `.wp-editor-wrap` (zero added specificity; utilities still apply).
const WP_EDITOR_SKIP = ':where(:not(.wp-editor-wrap, .wp-editor-wrap *))';

// Appends a zero-specificity condition to a selector's subject, before any
// pseudo-element.
function addCondition( selector, condition ) {
    if ( selector.includes( condition ) ) {
        return selector;
    }
    const at = selector.indexOf( '::' );

    return -1 === at ? selector + condition : selector.slice( 0, at ) + condition + selector.slice( at );
}

function skipWpEditor( selector ) {
    return /\.pui-root[\s>~+]/.test( selector ) ? addCondition( selector, WP_EDITOR_SKIP ) : selector;
}

// Legacy host (design.md D25): a screen still being migrated renders
// WpufProviders with `host`, so its ThemeProvider root gets `.wpuf-pui-host`.
// Inside it, plugin-ui styles reach only plugin-ui parts (`[data-slot]`),
// wrapper roots (`[data-wpuf-ui]`) and what is inside them; the screen's own
// markup keeps its look. Outside a host (portals, fully migrated screens)
// nothing changes.
const HOST = '.wpuf-pui-host';
const ISLAND = `:where(:not(${ HOST } *), [data-slot], [data-slot] *, [data-wpuf-ui], [data-wpuf-ui] *)`;

function island( selector ) {
    return /\.pui-root/.test( selector ) ? addCondition( selector, ISLAND ) : selector;
}

// Base rules on the root itself (font, color, line-height) do not apply to a
// host root, so they do not leak into its legacy markup by inheritance.
function rootBase( rule ) {
    const onlyVariables = rule.nodes.every( ( node ) => 'decl' !== node.type || node.prop.startsWith( '--' ) );

    if ( ! onlyVariables ) {
        rule.selectors = rule.selectors.map( ( selector ) => ( '.pui-root' === selector.trim() ? `.pui-root:not(${ HOST })` : selector ) );
    }
}

async function puiPart() {
    const from = join( here, 'src/pui.css' );
    const tree = postcss.parse( await compile( await readFile( from, 'utf8' ), from ) );
    const out = [];

    tree.walkComments( ( comment ) => comment.remove() );
    tree.each( ( node ) => {
        if ( 'atrule' !== node.type || 'layer' !== node.name ) {
            out.push( node.clone() );
            return;
        }
        if ( ! node.nodes ) {
            return;
        }
        if ( 'theme' === node.params ) {
            node.walkRules( ( rule ) => {
                rule.selectors = rule.selectors.map( ( selector ) => ( /^(:root|:host)$/.test( selector.trim() ) ? '.pui-root' : selector ) );
                rule.selectors = [ ...new Set( rule.selectors ) ];
            } );
        }
        if ( 'utilities' === node.params ) {
            node.walkRules( ( rule ) => {
                if ( skip( rule ) ) {
                    return;
                }
                rule.selectors = rule.selectors.flatMap( ( selector ) => {
                    const trimmed = selector.trim();
                    // `.pui-root .x` and the root itself (`.pui-root.x`).
                    return trimmed.startsWith( '.' )
                        ? [ `:where(.pui-root) ${ trimmed }`, `:where(.pui-root)${ trimmed }` ]
                        : [ `:where(.pui-root) ${ trimmed }` ];
                } ).map( island );
            } );
        }
        if ( 'theme' !== node.params && 'utilities' !== node.params ) {
            node.walkRules( ( rule ) => {
                rootBase( rule );
                rule.selectors = rule.selectors.map( skipWpEditor ).map( island );
            } );
        }
        node.each( ( child ) => out.push( child.clone() ) );
    } );

    // Unlayered rules of pui.css (WordPress forms.css resets).
    out.forEach( ( node ) => {
        if ( 'rule' === node.type ) {
            rootBase( node );
            node.selectors = node.selectors.map( skipWpEditor ).map( island );
        }
    } );

    return out;
}

async function build( name ) {
    const entry = ENTRIES[ name ];

    if ( ! entry ) {
        throw new Error( `Unknown entry "${ name }": ${ Object.keys( ENTRIES ).join( ', ' ) }` );
    }

    const from = join( here, entry.input );
    const part = async ( file ) => {
        const tree = postcss.parse( await compile( await readFile( join( here, file ), 'utf8' ), join( here, file ) ) );
        tree.walkComments( ( comment ) => comment.remove() );
        return tree.nodes;
    };
    const css = await compile( await readFile( from, 'utf8' ), from );
    let result = flatten( css, await part( entry.pre ), await part( entry.post ), entry.scope );

    if ( entry.pui ) {
        const pui = postcss.root();
        ( await puiPart() ).forEach( ( node ) => pui.append( node ) );
        // First in the file: with equal specificity the screen's own utilities
        // (classes a screen passes to a wrapper) then win over the plugin-ui
        // preflight, while plugin-ui's !important utilities still win.
        result = pui.toResult( { map: false } ).css + result;
    }

    // DataViews styles (generated src/pui-dataviews.css) for screens that list with it.
    if ( entry.dataviews ) {
        result += ( await compile( await readFile( join( here, 'src/pui-dataviews.css' ), 'utf8' ), join( here, 'src/pui-dataviews.css' ) ) );
    }
    const target = join( plugin, entry.output );

    // Bundled fonts (src/pui.css), relative to this stylesheet.
    result = result.split( '__WPUF_FONTS__' ).join( relative( dirname( target ), join( plugin, 'assets/fonts' ) ).split( '\\' ).join( '/' ) );

    await mkdir( dirname( target ), { recursive: true } );
    await writeFile( target, result );

    if ( entry.rtl ) {
        await writeFile( target.replace( /\.css$/, '-rtl.css' ), rtlcss.process( result ) );
    }

    console.log( `admin-css: ${ name } -> ${ relative( plugin, target ) } (${ Math.round( result.length / 1024 ) } KB)` );
}

